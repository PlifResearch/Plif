// Runs the real agent loop and the real Glob tool against a scratch project.
// The model is replaced by a recorder that returns a scripted reply, so no API
// call is made. The wire format (request, tool_use, tool_result) is the same
// one the Messages API uses.
import { mkdir, mkdtemp, realpath, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { runAgent } from "../dist/core/src/agent.js";
import { TOOLS } from "../dist/core/src/tools/index.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(here, "..", "docs", "demo", "glob-roundtrip.md");

const base = await realpath(await mkdtemp(path.join(tmpdir(), "plif-demo-")));
const root = path.join(base, "project");
for (const dir of ["src/deep", "docs"]) await mkdir(path.join(root, dir), { recursive: true });
await writeFile(path.join(root, "src/a.ts"), "export const a = 1;\n");
await writeFile(path.join(root, "src/b.tsx"), "export const B = () => null;\n");
await writeFile(path.join(root, "src/deep/c.ts"), "export const c = 3;\n");
await writeFile(path.join(root, "docs/readme.md"), "# docs\n");

const usage = { input_tokens: 0, output_tokens: 0 };
const script = [
  {
    id: "msg_demo_01",
    type: "message",
    role: "assistant",
    model: "claude-opus-5-5",
    content: [
      { type: "text", text: "I'll list the TypeScript files under src/ with size and date." },
      {
        type: "tool_use",
        id: "toolu_01DemoGlob0001",
        name: "Glob",
        input: { pattern: "src/**/*.{ts,tsx}", details: true, sort: "mtime" },
      },
    ],
    stop_reason: "tool_use",
    stop_sequence: null,
    usage,
  },
  {
    id: "msg_demo_02",
    type: "message",
    role: "assistant",
    model: "claude-opus-5-5",
    content: [{ type: "text", text: "There are 3 TypeScript files under src/; the newest is src/b.tsx." }],
    stop_reason: "end_turn",
    stop_sequence: null,
    usage,
  },
];

const requests = [];
const responses = [];
const model = {
  async create(params) {
    requests.push(structuredClone(params));
    const next = script.shift();
    responses.push(structuredClone(next));
    return next;
  },
};

const ctx = {
  root,
  home: path.join(base, "home"),
  session: "demo",
  sandbox: null,
  mode: { approval: "on-request", readOnly: false },
  readFiles: new Set(),
  approver: { ask: async () => false },
  log: { record: async () => {} },
};

const messages = [{ role: "user", content: "Which TypeScript files are in src/, and which changed most recently?" }];
const finalText = await runAgent({
  model,
  system: "(system prompt omitted in the demo)",
  tools: TOOLS,
  messages,
  ctx,
  maxTurns: 4,
});

const glob = TOOLS.find((tool) => tool.name === "Glob").definition;
const { tools: _tools, system: _system, messages: firstMessages, ...firstRest } = requests[0];
const second = requests[1];
const json = (value) => JSON.stringify(value, null, 2);

const sections = [
  "# Glob round trip",
  "",
  "This file is generated by `scripts/demo-tools.mjs`. It runs the real agent loop and the real Glob tool.",
  "The model is a recorder that returns a scripted reply, so no API call is made.",
  "",
  "## 1. Tool definition sent to the model",
  "",
  "The `tools` array sends each tool's name, description and `input_schema`. This is Glob's entry:",
  "",
  "```json",
  json(glob),
  "```",
  "",
  "## 2. Request 1: the model sees the user message and the tools",
  "",
  "```json",
  json({ ...firstRest, messages: firstMessages, tools: `[${requests[0].tools.map((tool) => tool.name).join(", ")}]` }),
  "```",
  "",
  "## 3. Response 1: the model asks for a tool",
  "",
  "`stop_reason` is `tool_use`. The `content` holds a text block and a `tool_use` block. The `id` is what the result must reference.",
  "",
  "```json",
  json({ stop_reason: responses[0].stop_reason, content: responses[0].content }),
  "```",
  "",
  "## 4. Request 2: the tool result goes back in a user message",
  "",
  "The assistant turn is sent back unchanged. Then a `user` message holds one `tool_result` per `tool_use`, with the same `tool_use_id`.",
  "",
  "```json",
  json(second.messages.slice(-2)),
  "```",
  "",
  "## 5. Final response",
  "",
  "```json",
  json({ stop_reason: responses[1].stop_reason, content: responses[1].content }),
  "```",
  "",
  `Final answer returned by the loop: ${JSON.stringify(finalText)}`,
  "",
];

const markdown = sections.join("\n");
await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, markdown, "utf8");
console.log(markdown);
console.log(`\nwritten to ${outFile}`);
